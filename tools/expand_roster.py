"""Stamp out many regional scout agents from a few templates — this is how the
roster scales toward 200 without hand-writing each one. It writes
`roster.generated.yaml`, which the runner merges with `roster.yaml` automatically.

    python tools/expand_roster.py           # generate (prints the count)
    python tools/expand_roster.py --clear    # delete the generated file

Add towns or roles below to grow the roster. Remember: more agents just means a
longer rotation — throughput is still capped by `daily_call_budget` in config.yaml,
so this never blows your free quotas.
"""
