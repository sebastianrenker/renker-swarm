def slug(text: str) -> str:
    text = text.lower()
    text = (text.replace("ae", "ae").replace("oe", "oe").replace("ue", "ue"))
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def build():
    agents = []
    for town in TOWNS:
        for role in ROLES:
            agents.append({
                "id": f"{role['suffix']}-{slug(town)}",
                "name": f"{role['name']} — {town}",
                "department": role["department"],
                "interval_minutes": role["interval"],
                "system": role["system"],
                "task": role["task"].format(town=town),
            })
    return agents


def main():
    if "--clear" in sys.argv:
        if OUT.exists():
            OUT.unlink()
            print(f"removed {OUT.name}")
        else:
            print("nothing to clear")
        return
    agents = build()
    header = ("# AUTO-GENERATED by tools/expand_roster.py — edit that script, not this.\n"
              "# Merged with roster.yaml at runtime.\n")
    OUT.write_text(header + yaml.safe_dump({"agents": agents}, allow_unicode=True,
                                           sort_keys=False), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(agents)} agents "
          f"({len(TOWNS)} towns x {len(ROLES)} roles)")


if __name__ == "__main__":
    main()
